const GERMANISH = /Gang|Stufen|Schaltgetriebe|sequenziell|Typ |Autosalon|Peking|Weltpremiere| bis | und | Jahre\b|Gutachten/;

/** English for a German data term; the input unchanged in German or when no translation exists. */
export function tr(s: string): string;
export function tr(s: string | undefined): string | undefined;
export function tr(s: string | undefined): string | undefined {
  if (!s || !isEn()) return s;
  const exact = EN[s];
  if (exact !== undefined) return exact;
  if (!GERMANISH.test(s)) return s;
  return RULES.reduce((acc, [re, rep]) => acc.replace(re, rep), s);
}

/** Paint name for display: German without the bracketed English name, English from the dictionary. */
export function paintName(name: string): string {
  return isEn() ? tr(name) : name.replace(/ \(.+\)$/, "");
}

